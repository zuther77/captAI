import Foundation

extension KeyCombo {
    /// ANSI-layout virtual key codes for letters and digits. Other keys fall back to `Key <code>`
    /// until the shortcut recorder (M1) maps them through the active keyboard layout.
    private static let ansiKeyNames: [UInt16: String] = [
        0: "A", 11: "B", 8: "C", 2: "D", 14: "E", 3: "F", 5: "G", 4: "H", 34: "I", 38: "J", 40: "K",
        37: "L", 46: "M", 45: "N", 31: "O", 35: "P", 12: "Q", 15: "R", 1: "S", 17: "T", 32: "U",
        9: "V", 13: "W", 7: "X", 16: "Y", 6: "Z",
        29: "0", 18: "1", 19: "2", 20: "3", 21: "4", 23: "5", 22: "6", 26: "7", 28: "8", 25: "9"
    ]

    /// macOS-style glyph string in the standard modifier order, for example `⌘⇧2`.
    var displayString: String {
        var result = ""
        if modifiers.contains(.control) { result += "⌃" }
        if modifiers.contains(.option) { result += "⌥" }
        if modifiers.contains(.shift) { result += "⇧" }
        if modifiers.contains(.command) { result += "⌘" }
        result += Self.ansiKeyNames[keyCode] ?? "Key \(keyCode)"
        return result
    }
}
